// Aufgabe 2 – Rechnen

// Erstelle:

// int a = 20;
// int b = 6;

// Gib aus:

// Addition
// Subtraktion
// Multiplikation
// Division
package chattyJava.src.tag1;

public class rechnen {
    public static void main(String[] args) {
        int a = 20;
        int b = 6;

        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
    }
}
