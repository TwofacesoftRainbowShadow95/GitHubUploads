# Praxisaufgabe
# Schreib ein Programm, das von 1 bis 5 zählt und jede Zahl ausgibt.
# Vorgabe: Verwende dafür eine while-Schleife.
# Kein for, kein range()

# Mein Plan 

# 1 & 2: Variable: x = 0 
# 3: while x < 5: 
# 4: x+=1 rauf itterieren
# 5: x < 5. Die Schleife läuft also, solange x kleiner als 5 ist. 
#    Durch x += 1 wird x irgendwann 5, wodurch die Bedingung False wird.
# 6: while ...
#     x += 1
#     print(...)

x = 0

while x < 5:
    x += 1
    print(x)